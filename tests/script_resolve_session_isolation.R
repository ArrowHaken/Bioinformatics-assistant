source('engine/sessions.R')
source('engine/dataset_profile.R')
source('engine/script_resolve.R')
root <- tempfile('script-scope-'); dir.create(file.path(root,'state'),recursive=TRUE)
on.exit <- NULL
write_json <- function(path,x) writeLines(jsonlite::toJSON(x,auto_unbox=TRUE,null='null'),path)
write_json(file.path(root,'state','remote_env.json'),list(script_lib=list(root='/A',files=list(list(file='A_ONLY.R',role='B_ONLY.R')))))
a <- sess_create(root,'A'); b <- sess_create(root,'B'); fresh <- sess_create(root,'new')
sess_set_identify(root,a$id,list(script_lib=list(root='/A',files=list(list(file='A_ONLY.R',role='B_ONLY.R')))))
sess_set_identify(root,b$id,list(script_lib=list(root='/B',files=list('B_ONLY.R'))))
fail <- character()
check <- function(label,value){cat(if(isTRUE(value)) 'PASS:' else 'FAIL:',label,'\n'); if(!isTRUE(value))fail<<-c(fail,label)}
probe <- function(sid) tryCatch(script_resolve_server_files(root,sid=sid),error=function(e)list(error=conditionMessage(e)))
x<-probe(a$id); check('A gets only file fields, not role text',identical(x$files,'A_ONLY.R')&&identical(x$root,'/A'))
x<-probe(b$id); check('B gets its own script list',identical(x$files,'B_ONLY.R')&&identical(x$root,'/B'))
x<-probe(fresh$id);check('new record never borrows latest probe',identical(x$known,FALSE)&&!length(x$files))
x<-probe('missing');check('unknown record remains unknown',identical(x$known,FALSE))
x<-probe('');check('empty owner never borrows global probe',identical(x$known,FALSE))
r<-tryCatch(script_resolve_all('',root,'one',function(id)list(script='A_ONLY.R'),function()list(),sid=b$id),error=function(e)NULL)
check('all resolver forwards B identity',!is.null(r)&&identical(r$stages[[1]]$on_server,'no'))
r<-script_resolve_one('one',list(script='X.R'),list(known=FALSE,files=character()),list(list(for_stage='one',id='lib')))
check('unknown server inventory is not claimed absent',!grepl('没找到',r$why,fixed=TRUE))
unlink(root,recursive=TRUE)
if(length(fail))stop(paste(length(fail),'script isolation failures'),call.=FALSE)
